import { z } from 'zod';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { MedasiumExport } from '../src/model/schema';
import { LAB_PANELS, LAB_TESTS, fmtRange, type LabTest } from '../src/model/labs';

type J = Record<string, any>;
const js = z.toJSONSchema(MedasiumExport, { target: 'draft-2020-12', io: 'input', unrepresentable: 'any' }) as J;

const rangeText = (t: LabTest) =>
  t.rangeBy ? `female ${fmtRange(t.rangeBy.female)}, male ${fmtRange(t.rangeBy.male)}` : fmtRange(t.range) || 'no default range (copy the report range)';
const altText = (t: LabTest) => (t.alt?.length ? `Convert: ${t.alt.map((a) => `${a.unit} x ${+a.factor.toPrecision(4)}`).join('; ')}.` : '');

// zod refinements are not exported to JSON Schema, so add the important ones explicitly.
const patched = { bp: 0, skip: 0, lab: 0 };
(function walk(n: any) {
  if (Array.isArray(n)) return n.forEach(walk);
  if (!n || typeof n !== 'object') return;
  const p = n.properties;
  if (p?.metric && p?.diastolic) {
    n.allOf = [
      { if: { properties: { metric: { const: 'bloodPressure' } }, required: ['metric'] }, then: { required: ['diastolic'] } },
      { if: { properties: { metric: { not: { const: 'bloodPressure' } } }, required: ['metric'] }, then: { not: { required: ['diastolic'] } } },
    ];
    patched.bp++;
  }
  if (p?.outcome && p?.taskId && p?.reason) {
    n.if = { properties: { outcome: { const: 'skipped' } }, required: ['outcome'] };
    n.then = { required: ['reason'], properties: { reason: { minLength: 1 } } };
    patched.skip++;
  }
  if (p?.test && p?.refLow && p?.qualifier) {
    // Self-describing catalogue: one const per test with its canonical unit, range and conversions.
    p.test = {
      description: p.test.description,
      oneOf: [
        ...LAB_TESTS.map((t) => ({ const: t.code, title: t.name, description: `${t.name} (${t.aliases.join(', ')}). Panel: ${t.panel}. Unit: ${t.unit}. Range: ${rangeText(t)}. ${altText(t)}`.trim() })),
        { const: 'custom', title: 'Custom test', description: 'Any test not in the catalogue. Requires name; give unit and the report range if printed.' },
      ],
    };
    n.allOf = [
      { oneOf: [{ required: ['value'], not: { required: ['text'] } }, { required: ['text'], not: { required: ['value'] } }] },
      { if: { required: ['qualifier'] }, then: { required: ['value'] } },
      { if: { required: ['abnormal'] }, then: { required: ['text'] } },
      { if: { properties: { test: { const: 'custom' } }, required: ['test'] }, then: { required: ['name'], properties: { name: { minLength: 1, pattern: '\\S' } } } },
      ...LAB_TESTS.map((t) => ({ if: { properties: { test: { const: t.code } }, required: ['test'] }, then: { properties: { unit: { const: t.unit } } } })),
    ];
    patched.lab++;
  }
  Object.values(n).forEach(walk);
})(js);
if (patched.bp !== 1 || patched.skip !== 1 || patched.lab !== 1) throw new Error(`schema patch failed: ${JSON.stringify(patched)}`);

js.$id = 'medasium.schema.json';
js.title = 'Medasium patient import/export file';
js.description =
  'One patient with profile, timeline entries (vitals, lab results, medications, observations, appointments, photos, task outcomes) and recurring tasks. ' +
  'India-first: IST (+05:30), mg/dL, °F, kg, cm, +91; lab values in each test\'s canonical unit. ' +
  'Not expressible in JSON Schema (the app also checks): entry ids unique; task ids unique; every task entry taskId matches a tasks[].id; lab refLow <= refHigh. Agent guide: ../agent/AGENTS.md';
mkdirSync('public/schema', { recursive: true });
writeFileSync('public/schema/medasium.schema.json', JSON.stringify(js, null, 1) + '\n');
console.log('wrote public/schema/medasium.schema.json');

// Lab catalogue table in the agent guide, generated so it can never drift from the code.
const md = (s: string) => s.replace(/\|/g, '\\|');
const table = LAB_PANELS.filter((pn) => pn.id !== 'custom').map((pn) => {
  const rows = LAB_TESTS.filter((t) => t.panel === pn.id).map((t) =>
    `| \`${t.code}\` | ${md(t.name)}${t.aliases.length ? ` (${md(t.aliases.join(', '))})` : ''} | ${md(t.unit)} | ${md(rangeText(t))}${t.sex ? ` · ${t.sex} only` : ''} | ${md(t.alt?.map((a) => `${a.unit} ×${+a.factor.toPrecision(4)}`).join(', ') ?? '')} |`);
  return [`**${pn.name}**`, '', '| code | test (aliases) | unit | typical range | other units → multiply by |', '|---|---|---|---|---|', ...rows].join('\n');
}).join('\n\n');
const guide = 'public/agent/AGENTS.md';
const doc = readFileSync(guide, 'utf8');
const START = '<!-- LAB_CATALOG:START (generated by scripts/gen-schema.ts; do not edit) -->', END = '<!-- LAB_CATALOG:END -->';
const a = doc.indexOf(START), b = doc.indexOf(END);
if (a < 0 || b < a) throw new Error('AGENTS.md is missing the LAB_CATALOG markers');
writeFileSync(guide, doc.slice(0, a + START.length) + '\n\n' + table + '\n\n' + doc.slice(b));
console.log(`wrote lab catalogue (${LAB_TESTS.length} tests) into ${guide}`);
